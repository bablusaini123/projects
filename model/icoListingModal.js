  twitterLink: { type: String ,},
  instagramLink: { type: String, },
  youtubeLink: { type: String ,},
  websiteLink: { type: String, },
  mediumLink: { type: String, },
  logo: { type: String, required: true },
  whitepaper: { type: String, required: true },
  roadmap: { type: String },
